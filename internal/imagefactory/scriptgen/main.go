// Command scriptgen emits immutable script constants, preserving LF pins.
package main

import (
	"fmt"
	"go/format"
	"os"
	"strings"
)

func main() {
	// Offline staging helpers are shared with temp-volume regression tests.
	names := [][2]string{{"makeISO", "make_iso.ps1"}, {"runnerExtract", "runner_extract.ps1"}, {"guestSetup", "guest_setup.ps1"}, {"guestVideo", "guest_video.ps1"}, {"videoFacts", "video_facts.ps1"}, {"stageSetup", "stage_setup.ps1"}, {"guestSpecialize", "guest_specialize.ps1"}, {"guestValidate", "guest_validate.ps1"}, {"imageSanitize", "image_sanitize.ps1"}, {"autologonSecret", "autologon_secret.ps1"}, {"inspectDisk", "inspect_disk.ps1"}, {"detachDisk", "detach_disk.ps1"}, {"runnerCheck", "runner_check.ps1"}, {"offlineFiles", "offline_files.ps1"}}
	var out strings.Builder
	names = append(names, [2]string{"offlinePayload", "offline_payload.ps1"})
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage imagefactory\n\n")
	for _, n := range names {
		b, err := os.ReadFile(n[1])
		if err != nil {
			panic(err)
		}
		if strings.ContainsRune(string(b), '\r') {
			panic("scripts must use LF")
		}
		fmt.Fprintf(&out, "const %s = %q\n\n", n[0], string(b))
	}
	b, err := format.Source([]byte(out.String()))
	if err != nil {
		panic(err)
	}
	if err = os.WriteFile("scripts_generated.go", b, 0600); err != nil {
		panic(err)
	}
}
